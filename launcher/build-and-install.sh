#!/usr/bin/env bash
# Build the launcher APK with the bare SDK tools (no Gradle) and install it on the TV as the home screen.
#   launcher/build-and-install.sh            build + install
#   launcher/build-and-install.sh --build    build only
set -euo pipefail
cd "$(dirname "$0")"
export JAVA_HOME="${JAVA_HOME:-/opt/homebrew/opt/openjdk@17}"
export PATH="$JAVA_HOME/bin:$PATH"
SDK="${ANDROID_HOME:-/opt/homebrew/share/android-commandlinetools}"
BT="$SDK/build-tools/34.0.0"
# Compile against API 28 (the Mi Box's Android 9) so newer API calls fail at build time, not on the box.
JAR="$SDK/platforms/android-28/android.jar"
B=build

rm -rf "$B" && mkdir -p "$B/gen" "$B/classes" "$B/dex"

# ESV API key: read from esv.env (git-ignored, one line ESV_API_KEY=<key>) and compiled into the
# APK through a generated class under build/. The key is never printed. ESV_ENV points at another
# file, e.g. ESV_ENV=/dev/null for a test build without the key.
ESV_ENV="${ESV_ENV:-esv.env}"
ESV_KEY=""
if [ -f "$ESV_ENV" ]; then
  ESV_KEY="$(sed -n 's/^[[:space:]]*ESV_API_KEY[[:space:]]*=//p' "$ESV_ENV" | tail -n 1 | tr -d "\"' \t\r")"
fi
case "$ESV_KEY" in
  *[!A-Za-z0-9]*) echo "ESV key: unexpected characters in $ESV_ENV, building without it" >&2; ESV_KEY="" ;;
esac
mkdir -p "$B/gen/com/mihir/tvhome"
printf 'package com.mihir.tvhome;\n\n/** Generated by build-and-install.sh from esv.env. Never commit. */\nfinal class EsvKey {\n    static final String KEY = "%s";\n}\n' \
  "$ESV_KEY" > "$B/gen/com/mihir/tvhome/EsvKey.java"
if [ -n "$ESV_KEY" ]; then echo "ESV key: found"; else echo "ESV key: missing (the verse card shows WEB until it is added)"; fi
unset ESV_KEY

# Calendar links: ICAL_URL_1..3 from calendar.env (git-ignored), compiled in the same way. Only
# the number found is printed. CAL_ENV points at another file, e.g. an empty one for a test build.
CAL_ENV="${CAL_ENV:-calendar.env}"
CAL_OUT="$B/gen/com/mihir/tvhome/CalendarLinks.java"
CAL_COUNT=0
printf 'package com.mihir.tvhome;\n\n/** Generated by build-and-install.sh from calendar.env. Never commit. */\nfinal class CalendarLinks {\n    static final String[] URLS = {\n' > "$CAL_OUT"
for n in 1 2 3; do
  url=""
  if [ -f "$CAL_ENV" ]; then
    url="$(sed -n "s/^[[:space:]]*ICAL_URL_$n[[:space:]]*=//p" "$CAL_ENV" | tail -n 1 | tr -d "\"' \t\r")"
  fi
  [ -n "$url" ] || continue
  case "$url" in
    https://*) ;;
    *) echo "Calendar link $n: not an https:// link, skipped" >&2; continue ;;
  esac
  case "$url" in
    *[!A-Za-z0-9:/?#@\&=%._~+,\;-]*) echo "Calendar link $n: unexpected characters, skipped" >&2; continue ;;
  esac
  printf '        "%s",\n' "$url" >> "$CAL_OUT"
  CAL_COUNT=$((CAL_COUNT + 1))
done
printf '    };\n}\n' >> "$CAL_OUT"
echo "Calendar links: $CAL_COUNT found"
unset url
"$BT/aapt2" compile --dir res -o "$B/res.zip"
"$BT/aapt2" link -o "$B/base.apk" -I "$JAR" --manifest AndroidManifest.xml --java "$B/gen" \
  -A assets --min-sdk-version 28 --target-sdk-version 30 "$B/res.zip"
javac -nowarn -Xlint:-options --release 11 -classpath "$JAR" -d "$B/classes" \
  $(find src "$B/gen" -name '*.java')
"$BT/d8" --min-api 28 --lib "$JAR" --output "$B/dex" $(find "$B/classes" -name '*.class')
cp "$B/base.apk" "$B/unsigned.apk"
(cd "$B/dex" && zip -q -u ../unsigned.apk classes.dex)
"$BT/zipalign" -f 4 "$B/unsigned.apk" "$B/aligned.apk"
[ -f debug.keystore ] || keytool -genkeypair -keystore debug.keystore -storepass android -keypass android \
  -alias tvhome -keyalg RSA -keysize 2048 -validity 10000 -dname "CN=tvhome" >/dev/null 2>&1
"$BT/apksigner" sign --ks debug.keystore --ks-pass pass:android --out "$B/tvhome.apk" "$B/aligned.apk"
echo "built $B/tvhome.apk ($(wc -c < "$B/tvhome.apk") bytes)"
[ "${1:-}" = "--build" ] && exit 0

PY=../tools/venv/bin/python
"$PY" -I ../tools/tv.py --push-b64 "$B/tvhome.apk" /data/local/tmp/tvhome.apk
printf '%s\n' \
  "pm install -r /data/local/tmp/tvhome.apk" \
  "rm -f /data/local/tmp/tvhome.apk" \
  "pm grant com.mihir.tvhome android.permission.ACCESS_FINE_LOCATION" \
  "cmd package set-home-activity --user 0 com.mihir.tvhome/.MainActivity" \
  "cmd package set-home-activity --user 0 com.mihir.tvhome/.MainActivity" \
  "am force-stop com.android.tv.settings" \
  "input keyevent KEYCODE_HOME" \
  | "$PY" -I ../tools/tv.py --batch
echo "Installed. Press Home on the remote."
